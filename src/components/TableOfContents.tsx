'use client';

import { useEffect, useState } from 'react';
import { useTranslations } from 'next-intl';

export interface TableOfContentsProps {
  html: string;
}

interface Heading {
  id: string;
  text: string;
  level: number;
}

/**
 * TableOfContents component that provides navigation for long pages
 * - Fixed position sidebar on xl screens (right side)
 * - Parses headings from content HTML
 * - Highlights active section on scroll
 * - Only shows if page has 3+ headings
 */
export function TableOfContents({ html }: TableOfContentsProps) {
  const t = useTranslations('toc');
  const [activeId, setActiveId] = useState<string>('');
  const [headings, setHeadings] = useState<Heading[]>([]);

  // Parse headings from HTML on the client side only (DOMParser not available during SSR)
  // Note: IDs are generated by EnhancedContent component
  useEffect(() => {
    const parser = new DOMParser();
    const doc = parser.parseFromString(html, 'text/html');
    const headingElements = doc.querySelectorAll('h2, h3');
    
    const parsedHeadings: Heading[] = [];
    headingElements.forEach((heading, index) => {
      const text = heading.textContent || '';
      // Generate ID from text (same logic as EnhancedContent)
      const baseId = text
        .toLowerCase()
        .replace(/[^\w\s-]/g, '')
        .replace(/\s+/g, '-')
        .replace(/^-+|-+$/g, '');
      
      // Check for duplicates
      const existingIds = parsedHeadings.map(h => h.id);
      let id = baseId;
      let counter = 1;
      while (existingIds.includes(id)) {
        id = `${baseId}-${counter}`;
        counter++;
      }
      
      if (!id) {
        id = `heading-${index}`;
      }
      
      parsedHeadings.push({
        id,
        text,
        level: parseInt(heading.tagName.substring(1)),
      });
    });
    
    // eslint-disable-next-line react-hooks/set-state-in-effect
    setHeadings(parsedHeadings);
  }, [html]);

  useEffect(() => {
    if (headings.length === 0) return;

    // Set up intersection observer to highlight active section
    const observer = new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          if (entry.isIntersecting) {
            setActiveId(entry.target.id);
          }
        });
      },
      {
        rootMargin: '-20% 0% -35% 0%',
        threshold: 0,
      }
    );

    // Observe all headings
    headings.forEach(({ id }) => {
      const element = document.getElementById(id);
      if (element) {
        observer.observe(element);
      }
    });

    return () => observer.disconnect();
  }, [headings]);

  // Only show if there are 3+ headings
  if (headings.length < 3) {
    return null;
  }

  const handleClick = (id: string) => {
    const element = document.getElementById(id);
    if (element) {
      element.scrollIntoView({ behavior: 'smooth', block: 'start' });
    }
  };

  return (
    <nav className="sticky top-28 max-h-[calc(100vh-9rem)] overflow-y-auto" aria-label={t('label')}>
      <p className="eyebrow mb-4">{t('label')}</p>
      <ul className="border-l border-line text-[15px]">
        {headings.map(({ id, text, level }) => (
          <li key={id}>
            <button
              onClick={() => handleClick(id)}
              className={`-ml-px block w-full text-left border-l py-1.5 transition-colors ${
                level === 3 ? 'pl-7' : 'pl-4'
              } ${
                activeId === id
                  ? 'border-accent text-ink'
                  : 'border-transparent text-muted hover:text-ink'
              }`}
            >
              {text}
            </button>
          </li>
        ))}
      </ul>
    </nav>
  );
}

export default TableOfContents;
